#ifndef MATHUTILS_H
#define MATHUTILS_H

namespace mathutils {

    // new fibonacci api
    long long fibonacci(int n);

    // Returns n! (n factorial). Defined as 1 for n <= 1.
    long long factorial(int n);

    // Returns the greatest common divisor of a and b.
    int gcd(int a, int b);
}

#endif // MATHUTILS_H
